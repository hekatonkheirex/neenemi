function normalizeText(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
}

export function searchParaguayMunicipalities(query: string): string[] {
  const normalizedQuery = normalizeText(query);
  const matches = normalizedQuery
    ? PARAGUAY_MUNICIPALITIES.filter((municipality) => normalizeText(municipality).includes(normalizedQuery))
    : [...PARAGUAY_MUNICIPALITIES];

  if (!normalizedQuery) return matches;

  return matches.sort((left, right) => {
    const leftStarts = normalizeText(left).startsWith(normalizedQuery);
    const rightStarts = normalizeText(right).startsWith(normalizedQuery);
    if (leftStarts !== rightStarts) return leftStarts ? -1 : 1;
    return left.localeCompare(right, 'es');
  });
}

export function canonicalMunicipality(value: string): string | undefined {
  const normalizedValue = normalizeText(value);
  return PARAGUAY_MUNICIPALITIES.find((municipality) => normalizeText(municipality) === normalizedValue);
}
